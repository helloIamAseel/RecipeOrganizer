export type TranslationKey = keyof typeof translations.en;

export function translateCategory(category: string, language: Language): string {
  if (language === 'en') return category;
  const map: Record<string, string> = {
    Breakfast: 'فطور',
    Lunch: 'غداء',
    Dinner: 'عشاء',
    Dessert: 'حلويات',
    Snack: 'وجبات خفيفة',
    Drink: 'مشروبات',
    Other: 'أخرى',
  };
  return map[category] || category;
}

export function formatMinutes(minutes: number, language: Language): string {
  if (language === 'en') return `${minutes} min`;

  const num = new Intl.NumberFormat('ar-SA').format(minutes);

  if (minutes === 1) return 'دقيقة واحدة';
  if (minutes === 2) return 'دقيقتان';
  if (minutes >= 3 && minutes <= 10) return `${num} دقائق`;
  return `${num} دقيقة`;
}